// scripts/seed-questions.mjs
//
// Seeds the MindSpark question bank from the curated Grade 5 lesson set in
// lib/m5Questions.json (M5 1301–1504, 72 questions across 5 levels).
// The same JSON feeds the offline fallback in lib/quizContent.ts.
//
//   node scripts/seed-questions.mjs           # write database/seed-questions.sql + self-check
//   node scripts/seed-questions.mjs --apply   # also reseed the local DB (reads .env.local)

import { writeFileSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const QUESTIONS_PER_PHASE = 5
const LETTERS = ['A', 'B', 'C', 'D']

// ─── Build rows ───────────────────────────────────────────────────────────────
// Phase split must match lib/quizContent.ts: alternate normal/boss through each
// level's questions so every lesson lands in both phases.
function buildRows() {
  const { levels } = JSON.parse(readFileSync(join(ROOT, 'lib', 'm5Questions.json'), 'utf8'))
  return levels.flatMap(({ level, lessons }) =>
    lessons
      .flatMap(({ category, questions }) => questions.map(q => ({ category, ...q })))
      .map((q, i) => ({
        level_number: level,
        phase: i % 2 === 0 ? 'normal' : 'boss',
        category: q.category,
        prompt: q.prompt,
        options: q.options,
        correctIndex: LETTERS.indexOf(q.answer),
      })),
  )
}

// ─── Self-check ───────────────────────────────────────────────────────────────
// Recomputed answers for the arithmetic items — catches answer-key typos
// (two were wrong in the source document: flour 2.25 kg, 10x5x2 prism 160 cm²).
const box = (l, w, h) => 2 * (l * w + l * h + w * h)
const COMPUTED = [
  ['1/2 + 1/4', '3/4'],
  ['2.5 + 1.75', '4.25'],
  ['3/4 ÷ 1/2', '1 1/2'],
  ['2.5 meters of ribbon', `${(2.5 - 0.75).toFixed(2)} m`],
  ['Maria has ₱500', `₱${(500 - 125.5 - 75.25).toFixed(2)}`],
  ['5.5 kg of flour', `${(5.5 - 1.75 - 1.5).toFixed(2)} kg`],
  ['collected ₱1,200', `₱${(1200 - 350.5 - 249.5) / 4}`],
  ['cube with an edge of 4 cm', `${6 * 4 * 4} cm²`],
  ['5 cm by 4 cm by 3 cm', `${box(5, 4, 3)} cm²`],
  ['cube has an edge of 6 cm', `${6 * 6 * 6} cm²`],
  ['7 cm, 5 cm, and 3 cm', `${box(7, 5, 3)} cm²`],
  ['base area of 25 cm²', `${25 + 4 * 15} cm²`],
  ['10 cm × 5 cm × 2 cm', `${box(10, 5, 2)} cm²`],
  ['edge of 8 cm', `${6 * 8 * 8} cm²`],
  ['radius of 5 cm', `${Math.round(4 * 3.14 * 25)} cm²`],
  ['radius of 6 cm and a slant height of 8 cm', `${(3.14 * 36 + 3.14 * 6 * 8).toFixed(2)} cm²`],
  ['cube has an edge of 7 cm', `${6 * 7 * 7} cm²`],
  ['edge of 10 cm', `${6 * 10 * 10} cm²`],
  ['10 cm × 5 cm × 4 cm', `${box(10, 5, 4)} cm²`],
  ['transport 85 balls', String(Math.ceil(85 / 10))],
]

function selfCheck(rows) {
  const buckets = {}
  for (const r of rows) {
    const key = `${r.level_number}-${r.phase}`
    ;(buckets[key] ??= []).push(r)
    if (r.options.length !== 4) throw new Error(`Bad option count in ${key}: ${r.prompt}`)
    if (r.correctIndex < 0) throw new Error(`Bad answer letter in ${key}: ${r.prompt}`)
    if (new Set(r.options).size !== 4) throw new Error(`Duplicate options in ${key}: ${r.prompt}`)
    if (r.category.length > 40) throw new Error(`Category over 40 chars: ${r.category}`)
  }
  for (let level = 1; level <= 5; level++) {
    for (const phase of ['normal', 'boss']) {
      const n = buckets[`${level}-${phase}`]?.length ?? 0
      if (n < QUESTIONS_PER_PHASE) throw new Error(`Level ${level} ${phase}: ${n} < ${QUESTIONS_PER_PHASE}`)
    }
  }
  for (const [needle, expected] of COMPUTED) {
    const hits = rows.filter(r => r.prompt.includes(needle))
    if (hits.length !== 1) throw new Error(`Check "${needle}" matched ${hits.length} rows`)
    const got = hits[0].options[hits[0].correctIndex]
    if (got !== expected) throw new Error(`Wrong answer: "${hits[0].prompt}" -> ${got}, expected ${expected}`)
  }
  return buckets
}

// ─── SQL emit ─────────────────────────────────────────────────────────────────
const esc = (s) => String(s).replace(/'/g, "''")
function toSQL(rows) {
  const header = `-- ============================================================
--  MindSpark Game — Question Bank Seed (Grade 5, M5 1301–1504)
--  ${rows.length} rows across 5 levels. Source: lib/m5Questions.json.
--  Generated by scripts/seed-questions.mjs.
--  created_by = NULL marks these as system seed rows.
--  Safe to re-run: clears prior seed rows (created_by IS NULL) first;
--  teacher-added questions are kept.
-- ============================================================

SET NAMES utf8mb4;

DELETE FROM quiz_questions WHERE created_by IS NULL;

INSERT INTO quiz_questions (level_number, phase, category, prompt, options, correct_index) VALUES
`
  const values = rows.map((r, i) => {
    const opts = esc(JSON.stringify(r.options))
    const end = i === rows.length - 1 ? ';' : ','
    return `(${r.level_number},'${r.phase}','${esc(r.category)}','${esc(r.prompt)}','${opts}',${r.correctIndex})${end}`
  })
  return header + values.join('\n') + '\n'
}

// ─── Main ─────────────────────────────────────────────────────────────────────
const rows = buildRows()
const buckets = selfCheck(rows)
const outPath = join(ROOT, 'database', 'seed-questions.sql')
writeFileSync(outPath, toSQL(rows), 'utf8')

console.log(`Self-check PASSED (${COMPUTED.length} arithmetic answers recomputed). Buckets:`)
for (const key of Object.keys(buckets).sort()) {
  const cats = [...new Set(buckets[key].map(r => r.category))]
  console.log(`  L${key.padEnd(8)} ${buckets[key].length} rows | ${cats.join(', ')}`)
}
console.log(`Wrote ${rows.length} rows -> ${outPath}`)

if (process.argv.includes('--apply')) {
  const env = {}
  try {
    for (const line of readFileSync(join(ROOT, '.env.local'), 'utf8').split(/\r?\n/)) {
      const m = line.match(/^([A-Z_]+)=(.*)$/)
      if (m) env[m[1]] = m[2].trim()
    }
  } catch { /* fall back to defaults */ }
  const mysql = (await import('mysql2/promise')).default
  const conn = await mysql.createConnection({
    host: env.DB_HOST || 'localhost',
    port: Number(env.DB_PORT || 3306),
    user: env.DB_USER || 'root',
    password: env.DB_PASSWORD || '',
    database: env.DB_NAME || 'mindsparkgame',
    charset: 'utf8mb4',
  })
  await conn.beginTransaction()
  await conn.query('DELETE FROM quiz_questions WHERE created_by IS NULL')
  const placeholders = rows.map(() => '(?,?,?,?,?,?)').join(',')
  const params = rows.flatMap(r => [r.level_number, r.phase, r.category, r.prompt, JSON.stringify(r.options), r.correctIndex])
  await conn.query(`INSERT INTO quiz_questions (level_number, phase, category, prompt, options, correct_index) VALUES ${placeholders}`, params)
  await conn.commit()
  const [[{ c }]] = await conn.query('SELECT COUNT(*) c FROM quiz_questions')
  console.log(`Applied to DB. quiz_questions now has ${c} rows.`)
  await conn.end()
}
